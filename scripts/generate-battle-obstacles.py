"""Compile factual obstacle footprints from a pinned original-data catalog."""
import hashlib,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=root/'references/secondary-skills-0.51/obstacles.json'
data=json.loads(re.sub(r',\s*([}\]])',r'\1',re.sub(r'//[^\n]*','',source.read_text())))
assets=json.loads((root/'assets/demo/manifest.json').read_text())['def']
terrains=['grass','dirt','sand','water','snow','swamp','rough','subterra','lava','rock']
rows=[]
for key,value in data.items():
 if value.get('absolute') or value['animation'].lower()not in assets:continue
 rows.append({'id':int(key),'asset':value['animation'].lower(),'terrainMask':sum(1<<terrains.index(t)for t in value.get('allowedTerrains',[])if t in terrains),'width':value['width'],'height':value['height'],'blocked':value['blockedTiles']})
cpp='// Original obstacle metadata; generated by scripts/generate-battle-obstacles.py.\n'
cpp+='struct NaturalObstacleDef {const char*asset;int terrain,width,height;std::vector<int>blocked;};\n'
cpp+='const std::vector<NaturalObstacleDef> NaturalObstacles={\n'
for r in rows:cpp+='{'+','.join([json.dumps(r['asset']),str(r['terrainMask']),str(r['width']),str(r['height']),'{'+','.join(map(str,r['blocked']))+'}'])+'},\n'
cpp+='};\n'
(root/'native/generated/battle_obstacles.inc').write_text(cpp)
(root/'data/native/battle-obstacles.json').write_text(json.dumps({'source':'https://raw.githubusercontent.com/vcmi/vcmi/948333932fdf91abda780906bf2d18eec9aa0fc1/config/obstacles.json','sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'obstacles':rows},indent=2)+'\n')
print('Compiled',len(rows),'original obstacle shapes')
