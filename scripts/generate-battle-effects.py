"""Compile original morale/luck effect assets; no engine implementation is used."""
import hashlib
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
reference = root / 'references/rules/vcmi/config/battles_graphics.json'
text = re.sub(r'//[^\n]*', '', reference.read_text())
mapping = {entry['id']: entry['defnames'] for entry in json.loads(text)['ac_mapping']}
demo = json.loads((root / 'assets/demo/manifest.json').read_text())
audio = json.loads((root / 'assets/audio/manifest.json').read_text())
rows = []
# Effect identities are factual constants in the pinned BattleConstants.h.
for key, original_id, sound in [('goodMorale', 20, 'goodmrle.wav'),
                                ('badMorale', 30, 'badmrle.wav'),
                                ('goodLuck', 18, 'goodluck.wav'),
                                ('badLuckSpell', 48, 'misfort.wav')]:
    name = mapping[original_id][0].lower()
    asset = demo['def'][name]
    frames = asset['groups']['0']
    canvas = frames[0]['canvas']
    assert frames and all(frame['canvas'] == canvas for frame in frames)
    assert sound in audio['sounds']
    for page in asset['pages']:
        assert (root / page['file']).is_file()
    rows.append({'key': key, 'originalEffectId': original_id, 'animation': name,
                 'frames': len(frames), 'canvas': canvas, 'frameMs': 100,
                 'assetSource': asset['source'], 'sound': sound,
                 'soundFileSha256': audio['sounds'][sound]['sha256']})

result = {'schema': 1, 'edition': 'Classic Complete / Shadow of Death',
          'sources': {'mapping': {'file': str(reference.relative_to(root)),
                                 'sha256': hashlib.sha256(reference.read_bytes()).hexdigest()},
                      'identity': 'references/battle/effect-source.json',
                      'frames': 'assets/demo/manifest.json', 'sounds': 'assets/audio/manifest.json'},
          'effects': rows,
          'limitations': ['100ms frame duration is provisional, not original-executable calibration.',
                          'The original canvases and offsets are retained; battlefield anchors need independent capture.',
                          'These original resolution sprites are not new native 2K artwork.',
                          'Bad luck animation is used only for Misfortune, not a classic negative-luck attack.']}
(root / 'data/native/battle-effects.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
cpp = ['// Generated by scripts/generate-battle-effects.py.']
for row in rows:
    cpp.append('{"%s",%d,%d,%d,%d},' % (row['animation'], row['frames'], *row['canvas'], row['frameMs']))
(root / 'native/generated/battle_effects.inc').write_text('\n'.join(cpp) + '\n')
print('Compiled', len(rows), 'original effects with', sum(row['frames'] for row in rows), 'frame references')

spells=json.loads((root/'data/native/spells.json').read_text())['spells']
cpp=['// Original timed-spell animation identities and frame canvases.']
records=[]
for spell in spells:
 animation=spell.get('animation',{});candidates=animation.get('affect',animation.get('hit',[]))
 candidates=[candidate if isinstance(candidate,str)else candidate.get('defName','')for candidate in candidates]
 names=[candidate.lower()+(""if candidate.lower().endswith('.def')else'.def')for candidate in candidates if isinstance(candidate,str)]
 name=next((name for name in reversed(names) if name in demo['def']),None)
 if name:
  asset=demo['def'][name];frames=asset['groups']['0'];w,h=frames[0]['canvas']
  cpp.append('{"%s",%d,%d,%d,100},'%(name,len(frames),w,h));records.append({'spell':spell['id'],'animation':name,'frames':len(frames),'canvas':[w,h]})
 else:cpp.append('{nullptr,0,0,0,100},')
(root/'native/generated/spell_effects.inc').write_text('\n'.join(cpp)+'\n')
(root/'data/native/spell-effects.json').write_text(json.dumps({'source':'data/native/spells.json','effects':records,'timing':'100 ms per frame; provisional original-executable calibration'},ensure_ascii=False,indent=2)+'\n')
print('Compiled',len(records),'timed-spell effects')
