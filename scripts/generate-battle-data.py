"""Compile original cell pixels, CRANIM facts and revision-pinned formations."""
import hashlib
import json
import pathlib
import re
import struct
from original_resources import OriginalResources
from h3_resources import png

root = pathlib.Path(__file__).resolve().parents[1]
resources = OriginalResources(root)
reference = root / 'references/rules/vcmi/config/gameConfig.json'
text = re.sub(r'//[^\n]*', '', reference.read_text())
configuration = json.loads(re.sub(r',\s*([}\]])', r'\1', text))
layout = configuration['settings']['combat']['layouts']['default']
formations = {}
for mode in ('Loose', 'Tight'):
    rows = [[cell // 17 for cell in row] for row in layout['attackerUnits' + mode]]
    assert len(rows) == 7 and all(len(row) == i + 1 for i, row in enumerate(rows))
    assert rows == [[cell // 17 for cell in row] for row in layout['defenderUnits' + mode]]
    formations[mode.lower()] = rows

destination = root / 'assets/demo/battle-ui'
destination.mkdir(parents=True, exist_ok=True)
masks, sources = {}, {}
for key, filename in [('ccellgrd.pcx', 'cell-grid.png'), ('ccellshd.pcx', 'cell-shadow.png')]:
    data = resources.read(key)
    size, width, height = struct.unpack_from('<III', data)
    assert (width, height, size) == (45, 52, 2340)
    pixels, palette = data[12:12 + size], bytearray(data[12 + size:12 + size + 768])
    alpha = bytearray([255] * 256)
    alpha[0] = 0
    if key == 'ccellshd.pcx':
        # Index 4 is a semantic shadow, not literal blue. Opacity still needs
        # independent original-executable calibration.
        palette[12:15] = bytes(3)
        alpha[4] = 80
    (destination / filename).write_bytes(png(width, height, pixels, palette, alpha))
    masks[key] = pixels
    sources[key] = resources.source(key)
mask_rows = [sum(1 << x for x in range(45) if masks['ccellgrd.pcx'][y * 45 + x] or masks['ccellshd.pcx'][y * 45 + x]) for y in range(52)]

raw = resources.read('cranim.txt')
reference_folder = root / 'references/battle'
reference_folder.mkdir(parents=True, exist_ok=True)
(reference_folder / 'cranim.txt').write_bytes(raw)
rows = [fields for line in raw.decode('cp1252').splitlines()[2:] if (fields := line.split('\t'))[0].strip()]
units = json.loads((root / 'data/native/creatures.json').read_text())['units']
units += [{'id':141+i,'originalId':original}for i,original in enumerate([146,147,148,145])]
timings = []
for unit in units:
    fields = rows[unit['originalId']]
    assert len(fields) >= 25 and all(0 <= float(fields[i]) <= 20 for i in range(4))
    timings.append({'unit': unit['id'], 'originalId': unit['originalId'], 'referenceName': fields[24],
                    'fidgetInterval': float(fields[0]), 'walkTime': float(fields[1]),
                    'attackTime': float(fields[2]), 'flightDistance': float(fields[3]),
                    'countOffset': int(fields[22]), 'attackClimax': int(fields[23]),
                    'missileOffsets': [float(x) for x in fields[4:10]],
                    'missileAngles': [float(x) for x in fields[10:22]]})
result = {'schema': 1, 'sources': {'cellPixels': sources, 'animation': resources.source('cranim.txt'),
          'formations': {'file': str(reference.relative_to(root)), 'sha256': hashlib.sha256(reference.read_bytes()).hexdigest(),
                         'revision': '5d048de14cb4d56e8cbfe3a221e10e88d9332e36'}},
          'hex': {'columnsPlayable': 15, 'rows': 11, 'originalColumns': 17, 'firstCellTopLeft': [36, 86],
                  'cellSize': [45, 52], 'columnPitch': 44, 'rowPitch': 42, 'oddRowXOffset': -22,
                  'originEvidence': '0.46 video frame-0900 and original siege coordinate grid resolve the one-column ambiguity; first playable cell starts at (36,86)'},
          'formations': formations, 'creatures': timings,
          'limitations': ['Original timing interpretation and complete action sequencing remain uncalibrated.',
                         'Shadow opacity, per-unit count offset interpretation and precise sprite anchors still need executable comparison.']}
(root / 'data/native/battle-layout.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
cpp = ['// Generated by scripts/generate-battle-data.py from original data and pinned formation facts.']
for name, values in formations.items():
    cpp.append('constexpr std::array<std::array<int,7>,7> ' + name + 'Rows{{' + ','.join('{' + ','.join(map(str, row)) + '}' for row in values) + '}};')
cpp.append('constexpr std::array<uint64_t,52> cellHitRows{' + ','.join('UINT64_C(' + hex(row) + ')' for row in mask_rows) + '};')
cpp.append('const std::array<CreatureAnimationTiming,UnitCount> CreatureAnimationTimings{{' + ','.join('{' + ','.join(str(value[key]) for key in ['fidgetInterval', 'walkTime', 'attackTime', 'flightDistance', 'countOffset', 'attackClimax']) + '}' for value in timings) + '}};')
(root / 'native/generated/battle_layout.inc').write_text('\n'.join(cpp) + '\n')
print('Compiled original battle cells, 14 formation rows and', len(timings), 'animation timing records')
